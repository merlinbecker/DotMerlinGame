// Builds the own test ROMs from tests/roms/src with the pinned RGBDS (research.md R11) and generates
// src/core/rom/logo-hash.generated.ts. Built ROMs go to tests/roms/build/ and are never committed.
//   node scripts/build-test-roms.ts
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { rgbdsPaths } from './fetch-rgbds.ts';

const SRC = 'tests/roms/src';
const OUT = 'tests/roms/build';
const LOGO_HASH_FILE = 'src/core/rom/logo-hash.generated.ts';

type Patch = 'header-checksum-zero' | 'break-logo' | 'break-header-checksum' | 'undefined-cart-type';

interface RomSpec {
  readonly source: string;
  readonly title: string;
  readonly defines?: Record<string, number>;
  /** Cartridge type for rgbfix -m (Pan Docs "The Cartridge Header", $0147). */
  readonly mbc?: string;
  /** RAM size code for rgbfix -r ($0149). */
  readonly ramSize?: string;
  readonly cgb?: 'only' | 'compatible';
  readonly patch?: readonly Patch[];
}

// Header offsets from Pan Docs "The Cartridge Header".
const LOGO_START = 0x0104;
const LOGO_END = 0x0133;
const CART_TYPE = 0x0147;
const MASK_ROM_VERSION = 0x014c;
const HEADER_CHECKSUM = 0x014d;
const GLOBAL_CHECKSUM = 0x014e;
/** Defined nowhere in the Pan Docs cartridge type table (between $03 and $05). */
const UNDEFINED_CART_TYPE = 0x04;

/** Pan Docs "014D — Header checksum". */
export function headerChecksum(rom: Uint8Array): number {
  let checksum = 0;
  for (let address = 0x0134; address <= 0x014c; address++) checksum = (checksum - (rom[address] ?? 0) - 1) & 0xff;
  return checksum;
}

/** Pan Docs "014E-014F — Global checksum": sum of all bytes except the checksum itself, big-endian. */
function writeGlobalChecksum(rom: Uint8Array): void {
  let sum = 0;
  rom.forEach((byte, index) => {
    if (index !== GLOBAL_CHECKSUM && index !== GLOBAL_CHECKSUM + 1) sum = (sum + byte) & 0xffff;
  });
  rom[GLOBAL_CHECKSUM] = sum >> 8;
  rom[GLOBAL_CHECKSUM + 1] = sum & 0xff;
}

export function applyPatch(rom: Uint8Array, patch: Patch): void {
  switch (patch) {
    case 'header-checksum-zero': {
      // Choose the mask ROM version byte so the header checksum becomes $00.
      for (let value = 0; value < 256; value++) {
        rom[MASK_ROM_VERSION] = value;
        if (headerChecksum(rom) === 0) break;
      }
      rom[HEADER_CHECKSUM] = headerChecksum(rom);
      break;
    }
    case 'break-logo':
      rom[LOGO_START + 8] = (rom[LOGO_START + 8] ?? 0) ^ 0xff;
      break;
    case 'break-header-checksum':
      rom[HEADER_CHECKSUM] = (rom[HEADER_CHECKSUM] ?? 0) ^ 0xff;
      break;
    case 'undefined-cart-type':
      rom[CART_TYPE] = UNDEFINED_CART_TYPE;
      rom[HEADER_CHECKSUM] = headerChecksum(rom);
      break;
  }
}

function build(name: string, spec: RomSpec, root: string): Uint8Array {
  const tools = rgbdsPaths(root);
  const object = join(OUT, `${name}.o`);
  const rom = join(OUT, `${name}.gb`);
  const defines = Object.entries(spec.defines ?? {}).flatMap(([key, value]) => ['-D', `${key}=${value}`]);
  execFileSync(tools.rgbasm, ['-I', SRC, ...defines, '-o', object, join(SRC, spec.source)], { stdio: 'inherit' });
  execFileSync(tools.rgblink, ['-o', rom, object], { stdio: 'inherit' });
  const fix = ['-v', '-p', '0xFF', '-t', spec.title];
  if (spec.mbc) fix.push('-m', spec.mbc);
  if (spec.ramSize) fix.push('-r', spec.ramSize);
  if (spec.cgb === 'only') fix.push('-C');
  if (spec.cgb === 'compatible') fix.push('-c');
  execFileSync(tools.rgbfix, [...fix, rom], { stdio: 'inherit' });

  const bytes = new Uint8Array(readFileSync(rom));
  for (const patch of spec.patch ?? []) applyPatch(bytes, patch);
  writeGlobalChecksum(bytes);
  writeFileSync(rom, bytes);
  return bytes;
}

function writeLogoHash(reference: Uint8Array): void {
  const digest = createHash('sha256').update(reference.subarray(LOGO_START, LOGO_END + 1)).digest('hex');
  writeFileSync(
    LOGO_HASH_FILE,
    [
      '// Generated by scripts/build-test-roms.ts from a ROM fixed by rgbfix. Do not edit by hand.',
      '// SHA-256 of the header logo $0104–$0133; the logo bytes themselves are not stored (ADR-0004).',
      `export const NINTENDO_LOGO_SHA256 = '${digest}';`,
      '',
    ].join('\n'),
  );
}

if (import.meta.main) {
  const root = resolve('.');
  const specs = JSON.parse(readFileSync(join(SRC, 'roms.json'), 'utf8')) as Record<string, RomSpec>;
  mkdirSync(OUT, { recursive: true });
  const built = new Map<string, Uint8Array>();
  for (const [name, spec] of Object.entries(specs)) built.set(name, build(name, spec, root));
  const reference = built.get('marker');
  if (!reference) throw new Error('reference ROM "marker" missing in roms.json');
  writeLogoHash(reference);
  console.log(`Built ${built.size} test ROMs into ${OUT} and wrote ${LOGO_HASH_FILE}`);
}
