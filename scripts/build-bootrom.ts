// Builds the own boot ROM with the pinned RGBDS into src/adapters/emulator/bootrom/generated/ (ADR-0004).
// The output is committed; npm run check rebuilds it and fails on any difference.
//   node scripts/build-bootrom.ts
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { RGBDS_VERSION, rgbdsPaths } from './fetch-rgbds.ts';

const SOURCE = 'src/adapters/emulator/bootrom/dmg-boot.asm';
const OUT = 'src/adapters/emulator/bootrom/generated';
const WORK = '.build/bootrom';
/** Pan Docs "Power Up Sequence": the DMG boot ROM is 256 bytes, mapped at $0000–$00FF. */
const BOOT_ROM_SIZE = 256;

export function renderModule(bytes: Uint8Array): string {
  const rows: string[] = [];
  for (let i = 0; i < bytes.length; i += 16) {
    rows.push('  ' + [...bytes.subarray(i, i + 16)].map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ',');
  }
  return [
    '// Generated by scripts/build-bootrom.ts from dmg-boot.asm. Do not edit by hand.',
    '// Own boot ROM (MIT), no Nintendo or third-party bytes (ADR-0004).',
    'export const DMG_BOOT_ROM = new Uint8Array([',
    ...rows,
    ']);',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const tools = rgbdsPaths(resolve('.'));
  mkdirSync(WORK, { recursive: true });
  mkdirSync(OUT, { recursive: true });
  const object = join(WORK, 'dmg-boot.o');
  const binary = join(WORK, 'dmg-boot.bin');
  execFileSync(tools.rgbasm, ['-o', object, SOURCE], { stdio: 'inherit' });
  execFileSync(tools.rgblink, ['-x', '-o', binary, object], { stdio: 'inherit' });
  const bytes = new Uint8Array(readFileSync(binary));
  if (bytes.length !== BOOT_ROM_SIZE) throw new Error(`Boot ROM must be ${BOOT_ROM_SIZE} bytes, got ${bytes.length}`);
  writeFileSync(join(OUT, 'dmg-boot.ts'), renderModule(bytes));
  const info = {
    component: 'DotMerlinGame boot ROM',
    source: SOURCE,
    rgbds: RGBDS_VERSION,
    size: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
  };
  writeFileSync(join(OUT, 'BUILD-INFO.json'), JSON.stringify(info, null, 2) + '\n');
  console.log(`Built ${OUT}/dmg-boot.ts (${bytes.length} bytes)`);
}
