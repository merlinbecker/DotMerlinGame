// Writes THIRD_PARTY_LICENSES and third_party/npm.md for all shipped (runtime) npm packages.
//   node scripts/generate-third-party.ts
import { writeFileSync } from 'node:fs';
import { PROJECT_NAME } from '../src/config/project.ts';
import { readLicenseText, readPackages } from './license-data.ts';

export function renderThirdPartyLicenses(): { licenses: string; table: string } {
  const packages = readPackages('runtime');

  const sections = packages.map((pkg) =>
    [
      `${pkg.name} ${pkg.version}`,
      `License: ${pkg.license ?? 'UNKNOWN'}`,
      `Source: ${pkg.repository ?? 'unknown'}`,
      '',
      readLicenseText(pkg),
    ].join('\n'),
  );
  const licenses = [
    `Third-party software shipped with ${PROJECT_NAME}.`,
    'Generated by scripts/generate-third-party.ts. Do not edit by hand.',
    '',
    sections.join('\n\n' + '-'.repeat(78) + '\n\n'),
    '',
  ].join('\n');

  const rows = packages.map(
    (pkg) => `| ${pkg.name} | ${pkg.version} | ${pkg.license ?? 'UNKNOWN'} | ${pkg.repository ?? 'unknown'} |`,
  );
  const table = [
    '# npm-Laufzeitabhängigkeiten',
    '',
    'Erzeugt von `scripts/generate-third-party.ts`, nicht von Hand bearbeiten. Lizenztexte stehen in',
    '`THIRD_PARTY_LICENSES`.',
    '',
    '| Paket | Version | Lizenz | Quelle |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');

  return { licenses, table };
}

if (import.meta.main) {
  const { licenses, table } = renderThirdPartyLicenses();
  writeFileSync('THIRD_PARTY_LICENSES', licenses);
  writeFileSync('third_party/npm.md', table);
  console.log('Wrote THIRD_PARTY_LICENSES and third_party/npm.md');
}
